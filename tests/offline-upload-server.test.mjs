test('resumable plans require strict attachment hashes, preserving legacy plans', () => {
 const input={uploadId:randomUUID(),metadata:{title:'fixture',date:'2026-10-28',participants:'',template:'standard'},sources:[],parts:[],transcript:'fixture',attachments:[{id:randomUUID(),name:'a.txt',size:3}]};
 assert.equal(UploadSchema.safeParse(input).success,false);
 assert.equal(UploadSchema.safeParse({...input,uploadId:undefined}).success,true);
 assert.equal(UploadSchema.safeParse({...input,attachments:[{...input.attachments[0],sha256:'a'.repeat(64)}]}).success,true);
});

test('accepted local replay stays idempotent while the original AI job is held', async t => {
 const dir=await mkdtemp(path.join(tmpdir(),'offline-held-'));let release;const held=new Promise(r=>{release=r;});let aiCalls=0;
 const {app,waitForJobs}=await createApp({dataDir:dir,apiKey:'fixture',aiFactory:()=>({transcribe:async()=>{aiCalls++;await held;throw new Error('fixture stop');}})});
 const server=app.listen(0,'127.0.0.1');await once(server,'listening');
 t.after(async()=>{release();await waitForJobs();await new Promise(r=>server.close(r));await rm(dir,{recursive:true,force:true});});
 const base=`http://127.0.0.1:${server.address().port}/api`;
 const bytes=new Uint8Array([1,2,3]);
 const input={uploadId:randomUUID(),metadata:{title:'held',date:'2026-10-28'},sources:[{name:'a.wav',size:3}],parts:[{name:'recording-1-1.wav',size:3,sourceIndex:0,partNumber:1,duration:1,sha256:createHash('sha256').update(bytes).digest('hex')}],attachments:[]};
 const post=(p,b)=>fetch(base+p,{method:'POST',headers:{'X-Kotonoha':'1','Content-Type':b instanceof Uint8Array?'application/octet-stream':'application/json'},body:b instanceof Uint8Array?b:JSON.stringify(b)});
 assert.equal((await post('/uploads',input)).status,201);
 assert.equal((await post(`/meetings/${input.uploadId}/parts?index=0`,bytes)).status,200);
 const completions=await Promise.all([post(`/meetings/${input.uploadId}/complete`,{}),post(`/meetings/${input.uploadId}/complete`,{})]);
 assert.deepEqual(completions.map(r=>r.status),[202,202]);
 assert.equal((await post('/uploads',input)).status,200);
 assert.equal((await post(`/meetings/${input.uploadId}/parts?index=0`,bytes)).status,200);
 assert.equal((await post(`/meetings/${input.uploadId}/complete`,{})).status,202);
 assert.equal(aiCalls,1);
});

test('resumable upload: lost init/part/complete responses replay one immutable owner-scoped upload and receipt', async t => {
  const dir = await mkdtemp(path.join(tmpdir(), 'offline-upload-'));
  const { app, waitForJobs } = await createApp({dataDir:dir, apiKey:'fixture-only', aiFactory:() => ({transcribe:async()=>{throw new Error('fixture no AI');}})});
  const server=app.listen(0,'127.0.0.1'); await once(server,'listening');
  t.after(async()=>{await new Promise(r=>server.close(r)); await waitForJobs(); await rm(dir,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${server.address().port}/api`;
  const call=(p,body)=>fetch(base+p,{method:'POST',headers:{'X-Kotonoha':'1','Content-Type':body instanceof Uint8Array?'application/octet-stream':'application/json'},body:body instanceof Uint8Array?body:JSON.stringify(body)});
  const bytes=new Uint8Array([1,2,3]);
  const input={uploadId:randomUUID(),metadata:{title:'fixture',date:'2026-10-28',participants:'',template:'standard'},sources:[{name:'test.wav',size:3}],parts:[{name:'recording-1-1.wav',size:3,sourceIndex:0,partNumber:1,duration:1,sha256:createHash('sha256').update(bytes).digest('hex')}],attachments:[]};
  const attachment={id:randomUUID(),name:'a.txt',size:3,sha256:createHash('sha256').update('abc').digest('hex')};
  input.attachments=[attachment];
  const inits=await Promise.all([call('/uploads',input),call('/uploads',input)]);
  assert.deepEqual(inits.map(r=>r.status).sort(),[200,201]);
  let response=inits.find(r=>r.status===201);
  assert.equal(response.status,201,await response.clone().text());
  const initial=await response.json();
  assert.equal(initial.id,input.uploadId);
  const identity=initial.uploadIdentity;
  assert.equal(identity.uploadId,input.uploadId); assert.ok(identity.ownerId); assert.match(identity.planDigest,/^[a-f0-9]{64}$/);
  response=await call('/uploads',input); assert.equal(response.status,200); assert.equal((await response.json()).id,initial.id);
  response=await call('/uploads',{...input,metadata:{...input.metadata,title:'changed'}}); assert.equal(response.status,409);
  const part=`/meetings/${initial.id}/parts?index=0`;
  const partResults=await Promise.all([call(part,bytes),call(part,bytes)]);
  assert.deepEqual(partResults.map(r=>r.status),[200,200]);
  assert.equal((await call(part,bytes)).status,200);
  assert.equal((await call(part,new Uint8Array([9,9,9]))).status,409);
  assert.equal((await call(`/meetings/${initial.id}/complete`,{})).status,409);
  const sendAttachment=(text='abc')=>{const form=new FormData();form.set('id',attachment.id);form.set('attachment',new File([text],'a.txt'));return fetch(base+`/meetings/${initial.id}/attachments`,{method:'POST',headers:{'X-Kotonoha':'1'},body:form});};
  const attachmentResults=await Promise.all([sendAttachment(),sendAttachment()]);
  assert.deepEqual(attachmentResults.map(r=>r.status).sort(),[200,201]);
  assert.equal((await sendAttachment()).status,200);
  assert.equal((await sendAttachment('xyz')).status,409);
  response=await call(`/meetings/${initial.id}/complete`,{}); assert.equal(response.status,202);
  const done=await response.json(); assert.deepEqual(done.uploadReceipt,{...identity,meetingId:initial.id,status:'accepted'});
  response=await call(`/meetings/${initial.id}/complete`,{}); assert.equal(response.status,202);
  assert.deepEqual((await response.json()).uploadReceipt,done.uploadReceipt);
  assert.equal((await (await fetch(base+'/meetings')).json()).length,1);
  const context=await (await fetch(base+'/uploads/context')).json(); assert.equal(context.ownerId,identity.ownerId); assert.equal(context.capabilities.resumableUpload,1);
  assert.equal((await (await fetch(base+`/meetings/${initial.id}`)).json()).uploadInput,undefined);
  await waitForJobs();
  assert.equal((await fetch(base+`/meetings/${initial.id}/attachments/${attachment.id}`,{method:'DELETE',headers:{'X-Kotonoha':'1'}})).status,200);
  assert.equal((await sendAttachment()).status,409);
  response=await call('/uploads',input); assert.equal(response.status,200); assert.equal((await response.json()).attachments.length,0);
  response=await call(`/meetings/${initial.id}/complete`,{}); assert.deepEqual((await response.json()).uploadReceipt,done.uploadReceipt);
  assert.equal((await fetch(base+`/meetings/${initial.id}`,{method:'DELETE',headers:{'X-Kotonoha':'1'}})).status,204);
  response=await call('/uploads',input); assert.equal(response.status,409,'deleted upload must not be recreated');
});
